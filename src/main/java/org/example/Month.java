package org.example;

/**
 * The twelve calendar months, in order from JANUARY to DECEMBER.
 * Used by DateChecker to decide how many days a month has.
 */
public enum Month {
    JANUARY,
    FEBRUARY,
    MARCH,
    APRIL,
    MAY,
    JUNE,
    JULY,
    AUGUST,
    SEPTEMBER,
    OCTOBER,
    NOVEMBER,
    DECEMBER
}
